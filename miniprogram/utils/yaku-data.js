function filterYakuCatalog({ category, query } = {}) {
  let result = YAKU_CATALOG;
  if (category) result = result.filter(yaku => yaku.category === category);
  if (query) {
    const q = query.toLowerCase();
    result = result.filter(yaku =>
      yaku.name.includes(query) ||
      yaku.condition.includes(query) ||
      (yaku.tags || []).some(tag => tag.includes(query))
    );
  }
  return result;
}

function getYakuById(id) {
  return YAKU_CATALOG.find(yaku => yaku.id === id) || null;
}

function formatYakuHan(yaku) {
  if (!yaku) return '';
  if (yaku.category === 'yakuman') return '役满';
  if (yaku.hanOpen === null) return `门前${yaku.hanClosed}翻 · 副露不可`;
  if (yaku.hanClosed === yaku.hanOpen) return `${yaku.hanClosed}翻`;
  return `门前${yaku.hanClosed}翻 · 副露${yaku.hanOpen}翻`;
}

// 返回该役种的牌例：hand（非胡牌张的 13 张）+ win（胡牌张，'' 表示等待任意一张）。
// 从 example 完整 14 张中抽出胡牌张单独展示（雀魂风格：一张隔开）。
function getYakuExample(yaku) {
  if (!yaku || !yaku.example || !yaku.example.length) return { hand: [], win: '' };
  const tiles = yaku.example[0].filter(Boolean);
  const win = yaku.win || '';
  if (!win) return { hand: tiles.slice(), win: '' };
  // 从手牌中抽出一张胡牌张（取最后一张，保持面子完整）
  const hand = tiles.slice();
  const idx = hand.lastIndexOf(win);
  if (idx >= 0) hand.splice(idx, 1);
  return { hand, win };
}

